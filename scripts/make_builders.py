"""Writes ``src/silverpoint/_builders.py`` and ``_builders.pyi`` from the pinned host catalog (PY-DD-03).

``--check`` fails when the checked-in files differ from what this script would write.
"""

from __future__ import annotations

import json
import keyword
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "src" / "silverpoint"
CATALOG = json.loads((PKG / "_vendor" / "host-catalog.json").read_text(encoding="utf-8"))
APPEARANCE = ("ground", "substrate", "mode", "palette")
FIXED = (*APPEARANCE, "width", "height", "id", "data")


def snake(name: str) -> str:
    return "".join(("_" + c.lower()) if c.isupper() and i else c.lower() for i, c in enumerate(name))


def options_of(chart):
    own = list(chart["options"])
    names = {o["name"] for o in own}
    return own + [o for o in CATALOG["common"] if o["name"] not in names]


def py_name(name: str, taken: set[str]) -> str:
    out = snake(name)
    if keyword.iskeyword(out) or out in taken:
        out += "_"
    return out


def annotation(option) -> str:
    if option["kind"] == "enum":
        return "Literal[" + ", ".join(json.dumps(v) for v in option["values"]) + "] | None"
    return {"boolean": "bool | None", "number": "float | None", "string": "str | None"}.get(
        option["kind"], "Any"
    )


def plan(chart):
    """Keywords in order: roles, then options; each as (python name, kind, catalog name, annotation)."""
    taken = set(FIXED)
    params = []
    for role in chart["roles"]:
        name = py_name(role["id"], taken)
        taken.add(name)
        hint = "str | Sequence[str] | None" if role["multiple"] else "str | None"
        params.append((name, "role", role["id"], hint, role))
    for option in options_of(chart):
        name = py_name(option["name"], taken)
        taken.add(name)
        params.append((name, "option", option["name"], annotation(option), option))
    return params


def docstring(chart, params) -> str:
    lines = [chart["summary"] or chart["title"], "", f"``{chart['slug']}`` ({chart['family']})."]
    roles = [p for p in params if p[1] == "role"]
    if roles:
        lines += ["", "Roles (column names):"]
        for name, _, _, _, role in roles:
            need = "required" if role["required"] else "optional"
            many = ", several" if role["multiple"] else ""
            lines.append(f"    {name}: {role['label']} — {role['kind']}, {role['dataType']}, {need}{many}.")
    own = [p for p in params if p[1] == "option" and p[4] in chart["options"]]
    if own:
        lines += ["", "Options:"]
        for name, _, _, _, option in own:
            doc = (" — " + option["doc"].replace("`", "``")) if option["doc"] else ""
            default = f" Default {json.dumps(option['default'])}." if "default" in option else ""
            lines.append(f"    {name}: {option['label']}{doc}{default}")
    return "\n".join(lines)


HEADER = '''"""Generated by ``scripts/make_builders.py`` from host catalog {version}. Do not edit."""
# ruff: noqa: E501

from __future__ import annotations
'''


def render_module(stub: bool) -> str:
    bindable = [c for c in CATALOG["charts"] if c["binding"] != "none"]
    out = [HEADER.format(version=CATALOG["version"])]
    out.append("from collections.abc import Sequence\nfrom typing import Any, Literal\n")
    out.append(
        "from .chart import Chart\n"
        if stub
        else "from typing import Any as _Any\n\nfrom .chart import Chart\n"
    )
    names = [c["slug"].replace("-", "_") for c in bindable]
    out.append("__all__ = [\n" + "".join(f'    "{n}",\n' for n in sorted(names)) + "]\n")
    if not stub:
        out.append("_NAMES: dict[str, dict[str, str]] = {}\n")
    look = {
        "ground": "Literal["
        + ", ".join(json.dumps(g["name"]) for g in CATALOG["appearance"]["grounds"])
        + "] | None",
        "substrate": "str | None",
        "mode": "Literal["
        + ", ".join(json.dumps(m["name"]) for m in CATALOG["appearance"]["modes"])
        + "] | None",
        "palette": "Literal["
        + ", ".join(json.dumps(p["name"]) for p in CATALOG["appearance"]["palettes"])
        + "] | None",
    }
    for chart, fn in zip(bindable, names, strict=True):
        params = plan(chart)
        sig = ["data: Any = None", "*"]
        sig += [f"{name}: {hint} = None" for name, _, _, hint, _ in params]
        sig += [f"{k}: {look[k]} = None" for k in APPEARANCE]
        sig += ["width: float | None = None", "height: float | None = None", "id: str | None = None"]
        head = f"def {fn}(\n" + "".join(f"    {s},\n" for s in sig) + ") -> Chart:"
        if stub:
            out.append(f"\n{head} ...\n")
            continue
        table = {name: f"{kind}:{original}" for name, kind, original, _, _ in params}
        doc = textwrap.indent(docstring(chart, params), "    ").lstrip()
        body = [
            f'    """{doc}\n    """',
            "    given = locals()",
            f'    return _build("{chart["slug"]}", "{fn}", given)',
        ]
        out.append(f'\n_NAMES["{fn}"] = {json.dumps(table)}\n\n\n{head}\n' + "\n".join(body) + "\n")
    if not stub:
        out.append("""

def _build(slug: str, fn: str, given: dict[str, _Any]) -> Chart:
    roles: dict[str, _Any] = {}
    options: dict[str, _Any] = {}
    for name, target in _NAMES[fn].items():
        value = given.get(name)
        if value is None:
            continue
        kind, original = target.split(":", 1)
        (roles if kind == "role" else options)[original] = value
    return Chart(
        slug,
        given.get("data"),
        roles=roles,
        options=options,
        ground=given.get("ground"),
        substrate=given.get("substrate"),
        mode=given.get("mode"),
        palette=given.get("palette"),
        width=given.get("width"),
        height=given.get("height"),
        id=given.get("id"),
    )
""")
    return "\n".join(out).replace("\n\n\n\n", "\n\n\n")


def formatted(text: str, name: str) -> str:
    """The module as ``ruff format`` writes it, so the checked-in file and ``--check`` agree."""
    ruff = shutil.which("ruff", path=str(Path(sys.executable).parent)) or shutil.which("ruff")
    if ruff is None:
        raise SystemExit("ruff is needed to write the builders: `uv sync` installs it")
    proc = subprocess.run(
        [ruff, "format", "--stdin-filename", str(PKG / name), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return proc.stdout


def main() -> int:
    files = {
        PKG / "_builders.py": formatted(render_module(False), "_builders.py"),
        PKG / "_builders.pyi": formatted(render_module(True), "_builders.pyi"),
    }
    if "--check" in sys.argv:
        stale = [
            p.name for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("stale:", ", ".join(stale), "— run `uv run python scripts/make_builders.py`")
            return 1
        print("builders current")
        return 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
